"""
Builds v0.1/SOURCES.md: every web link cited in v0.1's code and model files, and which
files cite it. Run it after changing sources so the index never goes stale:

    python tools/list_sources.py

It only reads comments/docstrings for links; it doesn't check that the links still work.
Namespace IRIs used inside the data (e.g. https://brickschema.org/schema/Brick#) are
identifiers, not sources, so they're skipped.
"""
import re
from collections import defaultdict
from pathlib import Path

V01 = Path(__file__).resolve().parents[1]
SCAN = ("*.py", "*.ttl", "*.txt", "*.conf", "*.yml")
SKIP_DIRS = {"venv", ".pytest_cache", "__pycache__"}
# Identifiers written in the data itself, not references to read.
NAMESPACES = re.compile(r"(^http://qudt\.org/|schema/Brick(/ref)?#|w3id\.org/rec#|qudt\.org/vocab/unit/$|"
                        r"XMLSchema#|rdf-schema#|owl#|skos/core#|2019/wot/modbus#?$)")
URL = re.compile(r"https?://[^\s\"'<>)`,]+")

cited = defaultdict(set)
for pattern in SCAN:
    for path in V01.rglob(pattern):
        if SKIP_DIRS & set(path.parts) or path == Path(__file__).resolve():
            continue                                     # skip this script's own patterns
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.lstrip().startswith("@prefix") or "PREFIX" in line:
                continue
            for url in URL.findall(line):
                url = url.rstrip(".;")
                if not NAMESPACES.search(url):
                    cited[url].add(path.relative_to(V01).as_posix())

lines = ["# Sources cited in v0.1 code and model files", "",
         "Generated by `python tools/list_sources.py`. Don't edit by hand.",
         "Design documents (README.md, mappings/DESIGN.md, NOTES.md files) have their own source lists.", "",
         "| Source | Cited in |", "|---|---|"]
for url in sorted(cited):
    lines.append(f"| <{url}> | {', '.join(f'`{f}`' for f in sorted(cited[url]))} |")
(V01 / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"SOURCES.md: {len(cited)} sources")
